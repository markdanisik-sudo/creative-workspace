def set_default(src, name, value):
    pattern = re.compile(r"^(DEFINE_UI_PARAMS\(%s,[^,]*,[^,]*,\s*)([^,]+)(,.*)$" % re.escape(name), re.M)
    if not pattern.search(src):
        raise KeyError(name)
    text = "%d" % value if isinstance(value, int) else "%g" % value
    if "." not in text and not isinstance(value, int):
        text += ".0"
    return pattern.sub(lambda m: m.group(1) + text + m.group(3), src, count=1)


def main():
    master = open(os.path.join(HERE, "FilmLab_Kodak.dctl")).read()
    out_dir = os.path.join(HERE, "looks")
    os.makedirs(out_dir, exist_ok=True)
    for look, params in LOOKS.items():
        src = master
        for name, value in params.items():
            src = set_default(src, name, value)
        src = src.replace("//  v1.0\n", "//  v1.0  |  LOOK PRESET: %s (generated by make_looks.py)\n" % look, 1)
        path = os.path.join(out_dir, "FilmLab_%s.dctl" % look)
        open(path, "w").write(src)
        print("wrote", os.path.relpath(path, HERE))


if __name__ == "__main__":
    main()
