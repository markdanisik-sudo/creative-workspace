"""Write the generated data block of FilmLab_Color.dctl (Film Lab v4).

    python3 export.py            # rewrites the block between the markers
    python3 export.py --check    # exit 1 if the DCTL is out of date

Everything comes from filmlab_model.py (Kodak curves and spectra digitised
in this folder, CIE standard tables, calibration_v4.json).
"""
import os, sys
import numpy as np
import filmlab_model as M

HERE = os.path.dirname(os.path.abspath(__file__))
DCTL = os.path.normpath(os.path.join(HERE, '..', 'FilmLab_Color.dctl'))
BEGIN = '// >>> generated by tools/export.py: do not edit by hand'
END = '// <<< generated'
S = M.S


def f(x):
    s = '%.7g' % x
    if 'e' in s:
        m, e = s.split('e')
        return (m if '.' in m else m + '.0') + 'e' + e + 'f'
    return (s if '.' in s else s + '.0') + 'f'


def arr(name, v, comment=''):
    v = np.asarray(v, float).ravel()
    return (f'// {comment}\n' if comment else '') + f'__CONSTANT__ float {name}[{len(v)}] = {{ {", ".join(f(x) for x in v)} }};'


def define(name, v, comment=''):
    return f'#define {name} ' + ', '.join(f(x) for x in np.ravel(v)) + (f'   // {comment}' if comment else '')


def block():
    o = [BEGIN, '//  Sources: Kodak H-1-5203 (50D), H-1-5207 (250D), VISION3 500T brochure, H-1-2383,',
         '//  digitised from the published graphs (dctl/tools/*.json, about +-0.01-0.02 D);',
         '//  CIE 1931 2-degree observer and CIE daylight (cie_standard.json); fits in',
         '//  calibration_v4.json.  [M] digitised Kodak, [D] derived, [F] fitted, [E] estimated.',
         f'#define NWL {len(M.WL)}   // 380-730 nm every 10 nm', '']

    dye_films = [M.FILMS[k] for k in M.DYE_SETS]
    o.append(arr('NEG_DYE_C', [fl.neg_dye[:, 0] for fl in dye_films], 'negative dyes [M], sets 250D (also 50D), 200T, 500T; NWL each'))
    o.append(arr('NEG_DYE_M', [fl.neg_dye[:, 1] for fl in dye_films]))
    o.append(arr('NEG_DYE_Y', [fl.neg_dye[:, 2] for fl in dye_films]))
    W = []
    for fl in dye_films:
        w = M.DATA['sens_2383'] * S['PRINTER_LAMP'][:, None] * (10.0 ** -fl.neg_dmin)[:, None]
        W.append(w / w.sum(0))
    o.append(arr('PRINT_W_R', [w[:, 0] for w in W], 'printer lamp [E: 3200 K] x negative base [M] x 2383 sensitivity [M], per dye set'))
    o.append(arr('PRINT_W_G', [w[:, 1] for w in W]))
    o.append(arr('PRINT_W_B', [w[:, 2] for w in W]))
    o.append(arr('NEG_AINV', [np.linalg.inv(fl.A_neg) for fl in dye_films], 'Status M density -> dye amounts, per dye set (Status M bands [F])'))
    o.append(arr('NEG_DMIN_M', [fl.neg_dmin_M for fl in dye_films], 'negative base, Status M, per dye set'))
    o.append('')

    F = M.REF
    pd = M.DATA['print_dye']
    o.append(arr('PRINT_DYE_C', pd[:, 0], '2383 dyes [M]'))
    o.append(arr('PRINT_DYE_M', pd[:, 1]))
    o.append(arr('PRINT_DYE_Y', pd[:, 2]))
    C = S['cmf']()
    light = S['XENON'] * 10.0 ** (-F.print_dmin)
    white = light @ C
    P = (S['XYZ_TO_2020'] @ S['cat'](white / white[1], S['D65_XYZ']) @ (C.T * light / white[1])).T
    o.append(arr('PROJ_R', P[:, 0], 'projector [E: 5800 K] x print base -> CIE 1931 [standard] -> D65 (CAT02) -> Rec.2020; clear print = 1'))
    o.append(arr('PROJ_G', P[:, 1]))
    o.append(arr('PROJ_B', P[:, 2]))
    o.append(define('PRINT_AINV', np.linalg.inv(F.A_print), 'Status A density -> print dye amounts (Status A bands [F])'))
    o.append(define('PRINT_DMIN_A', [F.print_fit[k][0] for k in 'RGB'], 'print base + fog, Status A [E: below the digitised range]'))
    for k in 'RGB':
        p = F.print_fit[k]
        o.append(define('PRINT_CURVE_' + k, [p[0], p[1], p[2], p[3], p[4]], 'dmin, dmax [extrapolated above 4.06], mid, steepness, shape s [F on M]'))
    o.append(define('LAD', M.LAD, 'laboratory aim density of 18% grey on 2383, Status A'))
    o.append('')

    rp = [M.FILMS[k].M_rp for k in M.SENS_SETS]
    o.append(arr('RP', rp, 'scene Rec.2020 -> layer exposure, degree-3 root polynomial (13 terms) per sensitivity set 50D / 200T / 250D / 500T [D/F on M]'))
    o.append(arr('SENS3', [M.FILMS[k].M_sens for k in M.SENS_SETS], 'the same as 3x3 matrices (only for the halation source)'))
    o.append(define('INTERIMAGE', M.CAL['interimage'], 'RG RB GR GB BR BG, on exposure-equivalent density [F: 250D scan]'))
    o.append(define('PRINT_XTALK', M.CAL['print_crosstalk'], 'RG RB GR GB BR BG, 2383 layer cross-talk [F: 2383 print]'))
    o.append('')

    rows = []
    o.append(f'#define NSTOCK {len(M.STOCKS)}')
    o.append('#define STOCK_STRIDE 22')
    o.append('#define SENS_NONE 4')
    o.append('// per stock: sensitivity set (0 50D, 1 200T, 2 250D, 3 500T, 4 none), dye set (0 250D, 1 200T, 2 500T), then per layer R, G, B')
    o.append('// dmin, gamma, toe, toe softness, shoulder, shoulder softness [F on M], halation gain, grain sigma (D) [E]')
    for key, label, sens, dyes, curves, hal, grain in M.STOCKS:
        n = M.Negative(key)
        rows.append([4 if sens is None else M.SENS_SETS.index(sens), M.DYE_SETS.index(dyes)] + list(n.P.ravel()) + [hal, grain])
        o.append(f'//   {key:10s} {M.STOCK_TAGS[key]}')
    o.append(arr('STOCKS', rows))
    o.append(f'#define STOCK_ORDER "{" ".join(s[0] for s in M.STOCKS)}"')
    o.append(END)
    return '\n'.join(o)


def main():
    src = open(DCTL).read()
    a, b = src.index(BEGIN), src.index(END) + len(END)
    new = src[:a] + block() + src[b:]
    if '--check' in sys.argv:
        sys.exit(0 if new == src else 1)
    open(DCTL, 'w').write(new)
    print('updated', os.path.relpath(DCTL))


if __name__ == '__main__':
    main()
